import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

for (const [format, code] of [
  ['CommonJS', "const path = require('node:path'); console.log(path.basename(__filename));"],
  ['ES module', "// Generated by Next\nimport path from 'node:path'; console.log(path.basename(import.meta.filename));"],
]) {
  test(`standalone launcher runs ${format} inside a module package`, async () => {
    const directory = await mkdtemp(join(tmpdir(), 'argus-standalone-'));
    try {
      await writeFile(join(directory, 'package.json'), '{"type":"module"}');
      await writeFile(join(directory, 'server.js'), code);
      const result = spawnSync(process.execPath, [
        fileURLToPath(new URL('./support/start-standalone.mjs', import.meta.url)), join(directory, 'server.js'),
      ], { encoding: 'utf8', timeout: 10000 });
      assert.equal(result.status, 0, result.stderr);
      assert.equal(result.stdout.trim(), format === 'CommonJS' ? 'server.cjs' : 'server.mjs');
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  });
}
